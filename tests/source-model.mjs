import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {bracketTree,propagate,reconstruct,fitLogistic,predict,timeline,logit} from '../scripts/source-model.mjs';
const leaf=id=>({ids:[id],round:-1});
const join=(left,right,round)=>({left,right,round,ids:[...left.ids,...right.ids]});
const tree=join(join(leaf('a'),leaf('b'),1),join(leaf('c'),leaf('d'),1),2);
const known={'a:b':.8,'c:d':.6,'a:c':.7,'a:d':.9,'b:c':.4,'b:d':.65};
const chance=(a,b)=>known[`${a}:${b}`]??1-known[`${b}:${a}`];
const open=propagate(tree,chance);
assert.ok(Math.abs(open[0].p[2]-.624)<1e-12,'Hand-calculated A title chance: .8*(.6*.7+.4*.9)');
const after=propagate(tree,chance,[{round:1,teamIds:['a','b'],winnerId:'b'}]);
assert.ok(Math.abs(after[1].p[2]-.5)<1e-12,'B title chance after beating A: .6*.4+.4*.65');
assert.equal(after[0].p[2],0);assert.equal(after[1].p[1],1);
const inverse=reconstruct(tree,open);
assert.ok(inverse.fit.maxError<1e-7,'Inverse reproduces synthetic advancement marginals');
for(const [pair,p]of Object.entries(inverse.matrix))assert.ok(Math.abs(p+inverse.matrix[pair.split(':').reverse().join(':')]-1)<1e-12);
assert.throws(()=>reconstruct(tree,open.slice(1)),/Complete field/);
const uninformative=fitLogistic(Array.from({length:100},(_,i)=>({x:[logit(.8)],y:i%2})),1);
assert.ok(Math.abs(predict(uninformative,[.8])-.5)<.025,'Fit corrects an overconfident uninformative source');
assert.ok(Math.abs(predict(uninformative,[.8])+predict(uninformative,[.2])-1)<1e-12,'Logistic reversal symmetry');
let checked=0;
for(const gender of ['mens','womens'])for(const year of [2016,2017,2018,2019,2021,2022,2023,2024,2025,2026]){
 const data=JSON.parse(await readFile(new URL(`../app/public/data/${gender==='womens'?'womens/':''}${year}.json`,import.meta.url)));
 const tree=bracketTree(data);
 const p=propagate(tree,()=>.5);
 for(let stage=0;stage<7;stage++)assert.ok(Math.abs(p.reduce((s,t)=>s+t.p[stage],0)-[64,32,16,8,4,2,1][stage])<1e-10);
 const all=propagate(tree,()=>.5,data.games);
 assert.equal(all.find(t=>t.id===data.championTeamId).p[6],1);
 for(const t of all)assert.ok(t.p.every(p=>p===0||p===1),'Completed tournament is exact');
 const matrix=Object.fromEntries(tree.ids.flatMap(a=>tree.ids.filter(b=>a!==b).map(b=>[`${a}:${b}`,.5])));
 const date=`${year}-03-01`;
 const before=timeline(data,matrix,date);
 const future=structuredClone(data);const final=future.games.find(g=>g.round===6);final.winnerId=final.teamIds.find(id=>id!==final.winnerId);
 const modified=timeline(future,matrix,date);
 assert.deepEqual(before.slice(0,-1),modified.slice(0,-1),'Future final cannot affect earlier odds');
 checked++;
}
console.log(`PASS: independent four-team arithmetic, inverse fit, complement symmetry, missing input rejection, logistic calibration, and ${checked} real brackets (64/68 teams), exact results, future-result isolation.`);

const {fitAt,historyReport}=await import('../scripts/ensemble.mjs');
const fixture=year=>({year,data:{games:[{id:`${year}-a`,teamIds:['a','b'],winnerId:'a'},{id:`${year}-b`,teamIds:['c','d'],winnerId:'d'}]},sources:[{id:'one',matrix:{'a:b':.7,'c:d':.6}}]});
const history=[2016,2017,2018,2019].map(fixture);
assert.equal(fitAt(history,['one'],2016).weights,null,'No fitting history => no ensemble');
assert.equal(fitAt(history,['one','new'],2019).weights,null,'A new source cannot acquire outcome-trained weights');
assert.deepEqual(fitAt(history,['one'],2018).years,[2016,2017]);
const mutated=structuredClone(history);mutated.filter(h=>h.year>=2018).forEach(h=>h.data.games.forEach(g=>g.winnerId=g.teamIds.find(id=>id!==g.winnerId)));
assert.deepEqual(fitAt(history,['one'],2018).weights,fitAt(mutated,['one'],2018).weights,'Current and future labels cannot influence fitted weights');
const report=historyReport(history,['one'],2019);
assert.deepEqual(report.folds.map(f=>f.year),[2017,2018]);
for(const fold of report.folds)assert.ok(fold.trainingYears.every(y=>y<fold.year));
assert.deepEqual(historyReport(history,['one'],2018),historyReport(mutated,['one'],2018),'Current/future outcomes cannot affect historical report');
console.log('PASS: first-year/new-source exclusions, strict training cutoffs, outcome mutation isolation, chronological historical tests.');
